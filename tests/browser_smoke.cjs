"use strict";
const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const html = fs.readFileSync("web/index.html", "utf8");
const script = html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(script, "browser application script exists");
new vm.Script(script[1], {filename: "web/index.html"});
const mockElement = {addEventListener() {}};
const context = {document: {getElementById() {return mockElement;}}};
vm.createContext(context);
vm.runInContext(script[1], context);
assert.equal(context.grade(3, 3, null, "biopsy").group, 1);
assert.equal(context.grade(3, 3, 5, "biopsy").group, 4);
assert.equal(context.grade(3, 4, 5, "prostatectomy").group, 2);
assert.equal(context.risk(2, 6, "T1c", 2, 12, null, null), "Favorable Intermediate Risk");
assert.equal(context.risk(2, 6, "T1c", null, null, null, null), "Intermediate Risk (subgroup undetermined)");
assert.equal(context.risk(2, 12, "T1c", 2, 12, null, null), "Unfavorable Intermediate Risk");
assert.equal(context.risk(5, 30, "T3b", null, null, null, null), "Very High Risk");
assert.equal(context.risk(1, 6, "T3b", null, null, null, null), "High Risk");
assert.equal(context.risk(4, 40, "T2a", null, null, null, null), "Very High Risk");
assert.throws(() => context.risk(1, -1, "T1c", null, null, null, null));
assert.equal(context.parseCSV('a,b\n"x,y",z\n').length, 2);
assert.match(context.csvCell("=1+1"), /^"'/);
console.log("Browser source syntax and logic smoke tests passed");
